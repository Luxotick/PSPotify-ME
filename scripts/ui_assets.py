"""Pinned fonts for the UI, shared by the PSP build and the PC preview.

fetch() downloads M PLUS Rounded 1c (three weights), the Lucide icon font
and the fonts' license into .deps/fonts. psp_fonts() then cuts them down to
the characters the UI bakes (see ui/font.c and ui/icons.h) and writes them
as C arrays the EBOOT links in: about 3.4 MB per weight becomes ~100 KB.
"""
from pathlib import Path
import hashlib
import io
import re
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / ".deps" / "fonts"
PSP_FONTS = FONTS / "psp"

GOOGLE_FONTS = ("https://raw.githubusercontent.com/google/fonts/"
                "84efd8ad78c3710ad14bd909e3bc407151885628/ofl/")
DOWNLOADS = {
    "MPLUSRounded1c-Regular.ttf": (GOOGLE_FONTS + "mplusrounded1c/MPLUSRounded1c-Regular.ttf",
        "b75708b53e45b06d17d470aeeca5b766e3d1b3999f03f13ec4eb863ca846c14c"),
    "MPLUSRounded1c-Bold.ttf": (GOOGLE_FONTS + "mplusrounded1c/MPLUSRounded1c-Bold.ttf",
        "c358630584e8e2d8fbd6121d0f4693255ffef6d1e6d4f3441fd6e5a963a11f9e"),
    "MPLUSRounded1c-ExtraBold.ttf": (GOOGLE_FONTS + "mplusrounded1c/MPLUSRounded1c-ExtraBold.ttf",
        "8e7c15901dca87f1451b356dda594f7d092ba252a5dcc47da74523a242493c36"),
    # The M+ fonts share one license file; the Rounded folder has none.
    "mplus-OFL.txt": (GOOGLE_FONTS + "mplus1p/OFL.txt",
        "da15da6b1496d4de18f97e2ad1b722ef8a1c121149c2c93b2cf7eac6ac27b35c"),
}
LUCIDE = ("https://registry.npmjs.org/lucide-static/-/lucide-static-1.48.0.tgz",
          "3c2ecda3d25f6a9692d83f8036d9a526f7da584a51af74cd16eda4498c5c33d8")

# Must match the slots in ui/font.c.
TEXT_CODEPOINTS = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) +
                   [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026,
                    0x2190, 0x2191, 0x2192, 0x2193, 0x25A1, 0x25B3, 0x25CB])
FACES = [("ui_font_regular", "MPLUSRounded1c-Regular.ttf"),
         ("ui_font_bold", "MPLUSRounded1c-Bold.ttf"),
         ("ui_font_xbold", "MPLUSRounded1c-ExtraBold.ttf"),
         ("ui_font_icons", "lucide.ttf")]


def download(url, sha256):
    with urllib.request.urlopen(url, timeout=120) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != sha256:
        raise RuntimeError(f"{url}: sha256 {digest} does not match the pin {sha256}")
    return data


def fetch():
    FONTS.mkdir(parents=True, exist_ok=True)
    for name, (url, sha256) in DOWNLOADS.items():
        target = FONTS / name
        if not target.exists():
            print(f"fetching {name}")
            target.write_bytes(download(url, sha256))
    icons = FONTS / "lucide.ttf"
    if not icons.exists():
        print("fetching lucide icons")
        with tarfile.open(fileobj=io.BytesIO(download(*LUCIDE)), mode="r:gz") as tar:
            icons.write_bytes(tar.extractfile("package/font/lucide.ttf").read())
            (FONTS / "lucide-LICENSE").write_bytes(tar.extractfile("package/LICENSE").read())


def icon_codepoints():
    header = (ROOT / "ui" / "icons.h").read_text(encoding="utf-8")
    return [int(cp, 16) for cp in re.findall(r"#define ICON_\w+\s+0x([0-9a-fA-F]+)u", header)]


def subset_face(symbol, name):
    """The TTF bytes of one face, cut down to the codepoints the UI draws."""
    from fontTools import subset

    options = subset.Options()
    options.layout_features = []
    options.hinting = False
    options.name_IDs = ["*"]         # keep copyright and license names
    options.notdef_outline = True
    font = subset.load_font(str(FONTS / name), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=icon_codepoints() if symbol == "ui_font_icons"
                       else TEXT_CODEPOINTS)
    subsetter.subset(font)
    buffer = io.BytesIO()
    subset.save_font(font, buffer, options)
    data = buffer.getvalue()
    print(f"{name}: {len(data)} bytes after subsetting")
    return data


def psp_fonts():
    """Subsets the fonts and returns the path of the generated C file."""
    fetch()
    PSP_FONTS.mkdir(parents=True, exist_ok=True)
    out = PSP_FONTS / "ui_fonts.c"
    lines = ["/* Generated by scripts/ui_assets.py: subset UI fonts. */", ""]
    for symbol, name in FACES:
        data = subset_face(symbol, name)
        lines.append(f"const unsigned char {symbol}[{len(data)}] __attribute__((aligned(4))) = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"const unsigned int {symbol}_len = {len(data)};")
        lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    return out
